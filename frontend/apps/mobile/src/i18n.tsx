const MESSAGES: Record<UiLang, Record<MessageKey, string>> = { vi, en, zh, ja, ko };

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function translate(lang: UiLang, key: MessageKey, vars?: Record<string, string | number>): string {
  let text = MESSAGES[lang]?.[key] ?? vi[key];
  for (const [name, value] of Object.entries(vars ?? {})) {
    text = text.split(`{${name}}`).join(String(value));
  }
  return text;
}

interface I18nValue {
  lang: UiLang;
  t: Translate;
}

const I18nContext = createContext<I18nValue>({ lang: "vi", t: (key, vars) => translate("vi", key, vars) });

export function I18nProvider({ lang, children }: { lang: UiLang; children: ReactNode }) {
  const value = useMemo<I18nValue>(
    () => ({ lang, t: (key, vars) => translate(lang, key, vars) }),
    [lang],
  );
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  return useContext(I18nContext);
}
